"""
luggage-agent/prompt.py
==================================================
统一的识别提示词（单一来源）。

【为什么要有这个文件】
之前 train.jsonl 里的 instruction 是一句短话，而 infer.py 用的是一段长提示词——
训练和推理"问法不同"，模型学的东西对不上，是导致输出混乱、过度预测的重要原因。
现在训练(train.py)与推理(infer.py / anno-tool)都从这里取同一段提示词，彻底对齐。
"""


def build_prompt(items):
    """给定额定物品清单，生成统一的识别提示词（训练 / 推理共用）。"""
    list_text = "、".join(items)
    return (
        "这是一张行李/出行物品照片（可能是收拾好的行李箱、桌面或房间，"
        "物品可能较多、较小、互相叠放）。请逐件仔细辨认画面中【真实可见】的实物。\n"
        "判断标准（务必从严）：\n"
        "1) 只有当你在画面中确实清楚看到该物品（或它的同类物）时，才把 present 标为 true，"
        "并给出文字位置（location，如'左侧内袋''桌上''化妆包'）；\n"
        "2) 只要不确定、看不清、或画面中没有，一律标 false，location 为 null。"
        "宁可漏判，也不要凭猜测标 true。\n"
        "3) 不要因为清单里有这一项就默认它存在；也可以整张照片全部为 false。\n"
        f"待检查物品：{list_text}。\n"
        "只返回一个 JSON，格式严格为："
        "{\"items\":[{\"name\":物品名,\"present\":true或false,\"location\":位置或null}]}"
    )

"""
luggage-agent/prompt.py
==================================================
统一的识别提示词（单一来源）。

【为什么要有这个文件】
之前 train.jsonl 里的 instruction 是一句短话，而 infer.py 用的是一段长提示词——
训练和推理"问法不同"，模型学的东西对不上，是导致输出混乱、过度预测的重要原因。
现在训练(train.py)与推理(infer.py / anno-tool 平台)都从这里取同一段提示词，彻底对齐。

【场景机制】
用户选定场景（旅行 / 上学回家）后，只把该场景的清单项交给模型：
  - 指令里写明场景名称，让模型知道该按哪套标准判断
  - 明确要求「清单以外的物品一律忽略」——这样旅行专属项（门票、相机…）
    在上学场景就不会被误报出来。
"""

# 场景代号 -> 中文名（与 taxonomy.json 的 scenarios 字段保持一致）
SCENARIOS = {
    "travel": "出门旅行 / 旅游",
    "school": "上学 / 回家",
}

DEFAULT_SCENARIO = "travel"


def scenario_name(scenario: str) -> str:
    return SCENARIOS.get(scenario, SCENARIOS[DEFAULT_SCENARIO])


def build_prompt(items, scenario: str = DEFAULT_SCENARIO) -> str:
    """给定该场景的物品清单，生成统一的识别提示词（训练 / 推理共用）。

    输出格式：**只列出画面里真的看到的物品**，没看到的一律不输出。
    「未带」= 清单减去已带，由程序算，不让模型生成。

    这样输出长度从「N 项 × (name+present+location)」≈700 token
    缩短成「实际看到的几项」≈80 token，任务从"复读长模板"变成"挑出看到的"，
    小样本下更容易学会真正看图判别。
    """
    list_text = "、".join(items)
    scene = scenario_name(scenario)
    return (
        f"这是一个「{scene}」场景的物品照片（可能是收拾好的行李箱、背包、桌面或房间，"
        "物品可能较多、较小、互相叠放）。请仔细辨认画面中【真实可见】的实物。\n"
        "任务：只把你在画面里确实看到的物品列出来；没看到的、不确定的一律不要列。\n"
        "判断标准（务必从严）：\n"
        "1) 只有当你在画面中确实清楚看到该物品（或它的同类物）时才列出，"
        "并给出文字位置（location，如'左侧内袋''桌上''书包侧袋'）；\n"
        "2) 只要不确定、看不清、或画面中没有，就不要列。宁可漏列，也不要凭猜测列。\n"
        "3) 不要因为清单里有这一项就默认它存在；如果一样都认不出来，就返回空列表。\n"
        "4) 只使用下面清单里的物品名，清单以外的不要输出，也不要自行补充。\n"
        f"待核对清单（共 {len(items)} 项）：{list_text}。\n"
        "注意：上面只是「要核对的名单」，绝大多数物品通常不在照片里，没看到的千万别列。\n"
        "只返回一个 JSON，格式严格为："
        "{\"items\":[{\"name\":物品名,\"location\":位置}]}\n"
        "一样都没看到时返回：{\"items\":[]}"
    )
